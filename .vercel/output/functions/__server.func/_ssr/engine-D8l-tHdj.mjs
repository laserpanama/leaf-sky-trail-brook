var KEY = "lqp-supplies";
var empty = {
	buy: {},
	yield: {},
	units: {},
	each: {},
	prepQty: {},
	specQty: {}
};
var bound = null;
/** Run costing reads and edits against a server copy. Nothing here touches the browser. */
function runWithStore(store, run) {
	bound = {
		...empty,
		...store ?? {}
	};
	try {
		return {
			result: run(),
			store: bound
		};
	} finally {
		bound = null;
	}
}
function read() {
	if (bound) return bound;
	if (typeof window === "undefined") return empty;
	try {
		const raw = window.localStorage.getItem(KEY);
		if (!raw) return empty;
		const parsed = JSON.parse(raw);
		return {
			...empty,
			...parsed
		};
	} catch {
		return empty;
	}
}
function write(store) {
	if (bound) {
		bound = store;
		return;
	}
	if (typeof window === "undefined") return;
	window.localStorage.setItem(KEY, JSON.stringify(store));
	window.dispatchEvent(new Event("lqp-supplies"));
}
function patch(group, key, value) {
	const store = read();
	const next = { ...store[group] };
	if (value === null) delete next[key];
	else next[key] = value;
	write({
		...store,
		[group]: next
	});
}
function supplyKey(book, id) {
	return `${book}:${id}`;
}
function listSupplies(book) {
	const store = read();
	return BOOKS[book].supplies.map((supply) => {
		const key = supplyKey(book, supply.id);
		return {
			...supply,
			buy: store.buy[key] ?? supply.buy,
			yield: store.yield[key] ?? supply.yield,
			units: store.units[key] ?? supply.units
		};
	});
}
function setSupplyBuy(book, id, buy) {
	const base = BOOKS[book].supplies.find((supply) => supply.id === id);
	patch("buy", supplyKey(book, id), base && buy === base.buy ? null : buy);
}
function setSupplyYield(book, id, yieldPct) {
	const base = BOOKS[book].supplies.find((supply) => supply.id === id);
	patch("yield", supplyKey(book, id), base && yieldPct === base.yield ? null : yieldPct);
}
function prepLines(book, prep) {
	const store = read();
	return prep.lines.map((line, index) => {
		const key = `${book}:${prep.id}:${index}`;
		return {
			...line,
			qty: store.prepQty[key] ?? line.qty,
			each: store.each[key] ?? line.each,
			key
		};
	});
}
function listPreps(book) {
	return BOOKS[book].preps.map((prep) => ({
		...prep,
		lines: prepLines(book, prep)
	}));
}
function setPrepEach(book, prepId, index, each) {
	const base = BOOKS[book].preps.find((item) => item.id === prepId)?.lines[index]?.each;
	patch("each", `${book}:${prepId}:${index}`, base === each ? null : each);
}
function setPrepQty(book, prepId, index, qty) {
	const base = BOOKS[book].preps.find((item) => item.id === prepId)?.lines[index]?.qty;
	patch("prepQty", `${book}:${prepId}:${index}`, base === qty ? null : qty);
}
function unitCost(book) {
	const supplies = listSupplies(book);
	const costs = {};
	for (const supply of supplies) {
		if (supply.kind !== "buy" || supply.buy == null) continue;
		const units = supply.units || 1;
		const yieldPct = supply.yield == null || supply.yield === 0 ? 1 : supply.yield;
		costs[supply.name] = supply.buy / (units * yieldPct);
	}
	for (const prep of listPreps(book)) {
		const batch = prep.lines.reduce((sum, line) => sum + line.qty * line.each, 0);
		costs[prep.name] = prep.yield ? batch / prep.yield : 0;
	}
	return costs;
}
var FOOD_ALIAS = {
	"Mini hamburguesa Quinta Pata": "Mini hamburguesa Quinta Pata (kids)",
	"Boneless de pollo, kids": "Boneless de pollo (kids)",
	"Pasta marinera o al olio": "Pasta marinera o al olio (kids)"
};
function itemCost(book, item) {
	const name = book === "cocina" ? FOOD_ALIAS[item] ?? item : item;
	const costs = unitCost(book);
	const store = read();
	const lines = BOOKS[book].specs.map((line, index) => ({
		...line,
		qty: store.specQty[`${book}:${index}`] ?? line.qty
	})).filter((line) => line.item === name);
	if (!lines.length) return null;
	let total = 0;
	let sideQty = 0;
	for (const line of lines) {
		if (line.supply === "Acompañamiento incluido (promedio)") {
			sideQty += line.qty;
			continue;
		}
		total += line.qty * (costs[line.supply] ?? 0);
	}
	if (sideQty > 0) total += sideQty * sideAverage(costs);
	return total;
}
function sideAverage(costs) {
	const sides = BOOKS.cocina.sides.map((name) => {
		return BOOKS.cocina.specs.filter((line) => line.item === name).reduce((sum, line) => sum + line.qty * (costs[line.supply] ?? 0), 0);
	}).filter((cost) => cost > 0);
	if (!sides.length) return 0;
	return sides.reduce((sum, cost) => sum + cost, 0) / sides.length;
}
function foodCost(name) {
	return itemCost("cocina", name);
}
function barCost(name) {
	return itemCost("barra", name);
}
function usesOf(book, supplyName) {
	const names = /* @__PURE__ */ new Set();
	for (const line of BOOKS[book].specs) if (line.supply === supplyName) names.add(line.item);
	for (const prep of BOOKS[book].preps) if (prep.lines.some((line) => line.name === supplyName) || prep.name === supplyName) {
		for (const line of BOOKS[book].specs) if (line.supply === prep.name) names.add(line.item);
	}
	return [...names];
}
